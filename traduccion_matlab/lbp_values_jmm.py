def lbp_values_jmm(orbit_Darts):

    # Constantes
    MAX = 4
    MIN = 0
    SLOPE = 2
    SADDLE = 3

    LBP_values = []

    for orbit in orbit_Darts:
        # Eliminar los -1 (valores de relleno)
        orbit = [x for x in orbit if x != -1]
        if len(orbit) == 0:
            LBP_values.append(-1)
            continue
        if len(orbit) >= 2:
            # Calcular número de transiciones
            trans = sum(abs(orbit[j] - orbit[j - 1]) for j in range(1, len(orbit)))

            if trans == 1 or trans == 2:
                LBP_values.append(SLOPE)
            elif trans == 0 and sum(orbit) == 0:
                LBP_values.append(MIN)
            elif trans == 0 and sum(orbit) > 0:
                LBP_values.append(MAX)
            elif trans > 2:
                LBP_values.append(SADDLE)
            else:
                LBP_values.append(-1)
        else:
            # Solo un elemento
            if orbit[0] == 1:
                LBP_values.append(MAX)
            else:
                LBP_values.append(MIN)
    return LBP_values


